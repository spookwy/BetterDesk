//! Захват ввода на клиенте и инжект на хосте.
//!
//! # Границы крейта
//!
//! Типы событий живут в [`bd_core::input`], а не здесь: событие видят
//! клиент, транспорт и хост, и общий словарь для них — ядро
//! (CLAUDE.md §4.2). Здесь — платформенная часть и логика состояния.
//!
//! # Что здесь есть
//!
//! - [`InputTracker`] — отслеживание зажатых клавиш. Портируемый,
//!   без `unsafe`. Решает критерий «ни одна клавиша не залипает»
//!   (docs/roadmap.md, этап 2).
//! - [`windows::InputInjector`] — инжект через `SendInput`.
//!
//! # Безопасность
//!
//! Инжект ввода — **первая по опасности поверхность атаки**
//! (docs/security-model.md §7.3, CLAUDE.md §8.5): он даёт полный
//! контроль над машиной. События применяются только из установленной
//! аутентифицированной сессии, а разбор недоверенных байтов происходит
//! в safe-коде ядра ([`bd_core::input::InputEvent::parse`]).

#![deny(unsafe_op_in_unsafe_fn)]
#![warn(missing_docs)]

mod error;
mod tracker;

#[cfg(windows)]
pub mod windows;

pub use error::{InputError, Result};
pub use tracker::{InputTracker, TrackOutcome};
