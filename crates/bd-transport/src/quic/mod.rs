//! QUIC-транспорт: настоящая сеть вместо заглушки.
//!
//! # Устройство
//!
//! QUIC асинхронен, пайплайн синхронен. Соединяет их **выделенный
//! поток** с однопоточным рантаймом tokio; общение — через каналы
//! (обоснование целиком — docs/adr/0002).
//!
//! ```text
//! поток пайплайна                 поток QUIC (tokio)
//! ───────────────                 ──────────────────
//! send(кадр)   ──► канал ──►      фрагментация → datagram
//! receive()    ◄── канал ◄──      datagram → сборка кадра
//! ```
//!
//! Ни `send`, ни `receive` не блокируются: пайплайн не ждёт сети
//! никогда. Переполнение канала отправки означает, что сеть не
//! успевает, — и тогда кадр **отбрасывается**, а не копится
//! (CLAUDE.md §5.3).
//!
//! # Что осталось от заглушки
//!
//! Всё, кроме доставки: wire-формат ([`crate::packet`]), фрагментация
//! и сборка ([`crate::fragment`]), счётчики. Так было задумано на
//! этапе 1 (docs/adr/0001) — и здесь это окупается: отлаживать
//! пришлось только сеть.

