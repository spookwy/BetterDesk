//! Пробивание NAT: встречные пакеты с того же сокета, где пойдут данные.
//!
//! # Что мешает соединиться через интернет без этого
//!
//! Обе стороны обычно за NAT, и ни одна не может просто «принять
//! входящее»: роутер отбрасывает пакет, для которого он не заводил
//! отображения. Отображение появляется, только когда изнутри уходит
//! пакет наружу — тогда роутер запоминает пару «внутренний адрес ↔
//! внешний порт» и пропускает ответы на неё.
//!
//! Отсюда приём, который и называется hole punching: **обе стороны
//! шлют друг другу пакеты одновременно**. Первые почти наверняка
//! пропадут — отображения у собеседника ещё нет, — но каждый из них
//! открывает дырку со своей стороны. Через один-два обмена пакеты
//! начинают доходить.
//!
//! # Почему это не заработало раньше
//!
//! Сигналинг ходит по своему TCP-сокету, QUIC слушает свой UDP-порт,
//! и связи между ними не было (находка 59). Роутер открывает
//! отображение для **конкретного порта**, поэтому бить надо с того
//! самого сокета, на котором потом пойдут данные, — иначе дырка
//! откроется не там, где нужно.
//!
//! Здесь сокет создаётся заранее, пробивается им же и **отдаётся
//! quinn готовым** (`quinn::Endpoint::new` это позволяет). Это
//! единственная причина, по которой модуль вообще существует
//! отдельно от `quic::endpoint`.
//!
//! # Чего этот модуль не делает
//!
//! Это не ICE. Настоящий ICE перебирает пары кандидатов (локальные,
//! рефлексивные, релейные), проверяет их STUN-запросами и выбирает
//! лучшую. Здесь одна пара адресов, полученная от сигналинга, и
//! простое пробивание.
//!
//! Такой подход **не покрывает symmetric NAT**: он выдаёт новый
//! внешний порт на каждый адрес назначения, поэтому порт, который
//! сервер увидел у нас, не тот, что увидит пир. Это записанное
//! ограничение, а не недосмотр: по §5.4 таким соединениям нужен
//! TURN-релей, отложенный до появления бюджета. Ожидаемая
//! успешность прямого соединения — 80–85 %.

use std::net::{SocketAddr, UdpSocket};
use std::time::{Duration, Instant};

use crate::{Result, TransportError};

/// Что слать в пробивающем пакете.
///
/// Содержимое не имеет значения — важен сам факт исходящего пакета,
/// открывающего отображение в роутере. Но пакет должен быть
/// **опознаваемым**: он прилетит в тот же сокет, где потом пойдёт
/// QUIC, и приёмник обязан отличить его от начала рукопожатия.
///
/// Восемь байт с явной сигнатурой: короткие случайные датаграмы QUIC
/// не начинаются с такого, а человек, глядящий в дамп трафика,
/// сразу поймёт, что это.
const PUNCH_MAGIC: &[u8] = b"BDPUNCH\x01";

/// Сколько пакетов отправить и с каким шагом.
///
/// # Почему несколько, а не один
///
/// Первый пакет почти наверняка пропадёт: у собеседника отображения
/// ещё нет, и его роутер пакет отбросит. Смысл серии в том, чтобы
/// обе стороны успели открыть свои дырки — после чего доходить
/// начинают уже оба направления.
///
/// Двадцать пакетов с шагом 50 мс — это секунда попыток. Дольше
/// ждать бессмысленно: если за секунду встречного движения не
/// случилось, дело не в потерях, а в том, что NAT симметричный или
/// сторона не отвечает вовсе.
const PUNCH_ATTEMPTS: usize = 20;

/// Пауза между пробивающими пакетами.
const PUNCH_INTERVAL: Duration = Duration::from_millis(50);

/// Сколько ждать ответного пробивающего пакета.
///
/// Совпадает с длительностью серии: ждать дольше, чем шлём, незачем —
/// собеседник к этому моменту либо начал бить, либо не начнёт.
const PUNCH_TIMEOUT: Duration = Duration::from_secs(1);

/// Превратить адрес сокета в адрес, по которому можно достучаться.
///
/// `0.0.0.0` (и `::`) — это не адрес, а указание слушать на всех
/// интерфейсах. Сообщать его собеседнику бессмысленно: пакет туда не
/// отправить. Порт при этом настоящий и меняться не должен — именно
/// на нём открыто отображение в NAT.
///
/// # Как узнаётся настоящий адрес
///
/// Через UDP-«соединение» с внешним адресом. Датаграмы при этом **не
/// отправляются**: `connect` на UDP лишь просит ядро выбрать маршрут,
/// а вместе с ним — исходящий интерфейс. Его адрес и нужен.
///
/// Способ работает без сети (маршрут берётся из таблицы
/// маршрутизации, а не из доступности узла) и не требует перечисления
/// интерфейсов, где пришлось бы гадать, какой из них «тот самый» на
/// машине с VPN, Hyper-V и парой адаптеров.
///
/// # Зачем это здесь
///
/// Живой прогон по ID показал, что хост объявлял себя как
/// `0.0.0.0:7000`, и клиент честно бил в никуда. Обе стороны нуждаются
/// в одном и том же преобразовании, поэтому оно лежит рядом с
/// пробиванием, а не копируется в двух бинарях.
pub fn reachable_addr(addr: SocketAddr) -> SocketAddr {
    if !addr.ip().is_unspecified() {
        // Адрес задан явно — человек знает, что делает.
        return addr;
    }

    // Куда «соединяться» — неважно, лишь бы адрес был внешним: ядру
    // нужен маршрут, а не собеседник. 203.0.113.0/24 зарезервирован
    // под примеры (RFC 5737), то есть заведомо ничей.
    let probe = UdpSocket::bind("0.0.0.0:0").and_then(|s| {
        s.connect("203.0.113.1:9")?;
        s.local_addr()
    });

    match probe {
        Ok(local) => SocketAddr::new(local.ip(), addr.port()),
        Err(e) => {
            // Не удалось — отдаём как есть. Хуже не станет:
            // соединение по внешнему адресу от этого не зависит.
            tracing::debug!(?e, "не удалось определить локальный адрес");
            addr
        }
    }
}

/// Итог пробивания.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PunchOutcome {
    /// Пришёл встречный пакет — дырка открыта с обеих сторон.
    ///
    /// Это не гарантия, что QUIC соединится (сторона могла умереть
    /// сразу после), но лучшее подтверждение, которое здесь возможно.
    Opened,
    /// Ответа не было. Соединяться всё равно стоит: наши пакеты
    /// открыли дырку с нашей стороны, и если у пира NAT мягкий или
    /// его вовсе нет, рукопожатие пройдёт.
    NoAnswer,
}

/// Пробить NAT в сторону пира сокетом, который потом отдадут QUIC.
///
/// Сокет **не потребляется**: он возвращается вызывающему в том же
/// виде, чтобы уйти в `quinn::Endpoint::new`. В этом весь смысл —
/// отображение в роутере заведено именно для его порта.
///
/// # Ошибки
///
/// Только на неустранимых сбоях сокета. Отсутствие ответа ошибкой
/// **не является** и возвращается как [`PunchOutcome::NoAnswer`]:
/// решение, продолжать ли, принимает вызывающий, и обычно продолжать
/// стоит.
pub fn punch(socket: &UdpSocket, peer: SocketAddr) -> Result<PunchOutcome> {
    // Неблокирующий режим: иначе `recv_from` встал бы до первого
    // пакета, и мы перестали бы слать свои — то есть перестали бы
    // делать ровно то, ради чего пришли. Пробивание требует
    // одновременности, а не очерёдности.
    socket
        .set_nonblocking(true)
        .map_err(|e| TransportError::Setup(format!("неблокирующий режим сокета: {e}")))?;

    let started = Instant::now();
    let mut buf = [0u8; 64];
    let mut answered = false;

    for attempt in 0..PUNCH_ATTEMPTS {
        // Ошибку отправки не считаем фатальной: «сеть недостижима»
        // на одной попытке — обычное дело при поднимающемся
        // интерфейсе, а серия на то и серия.
        if let Err(e) = socket.send_to(PUNCH_MAGIC, peer) {
            tracing::trace!(?e, attempt, "пробивающий пакет не ушёл");
        }

        // Забираем всё, что успело прийти, до следующей отправки.
        let deadline = Instant::now() + PUNCH_INTERVAL;
        while Instant::now() < deadline {
            match socket.recv_from(&mut buf) {
                Ok((len, from)) => {
                    if &buf[..len] == PUNCH_MAGIC {
                        tracing::info!(%from, attempt, "встречный пакет — дырка открыта");
                        answered = true;
                        // Не выходим сразу: пир мог ещё не получить
                        // ни одного нашего пакета, и бросив серию, мы
                        // оставили бы его дырку незаведённой. Дошлём
                        // остаток — это дешевле, чем несостоявшееся
                        // соединение.
                    } else {
                        // Не наш пакет. Скорее всего это уже QUIC:
                        // пир закончил пробивать и начал рукопожатие.
                        // Датаграм потерян, но QUIC переотправит —
                        // потери на старте для него норма.
                        tracing::debug!(%from, len, "непробивающий пакет во время пробивания");
                    }
                }
                Err(ref e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                    // Пусто — это норма, а не ошибка. Спим коротко,
                    // чтобы не жечь процессор опросом.
                    std::thread::sleep(Duration::from_millis(2));
                }
                // `ConnectionReset` на UDP — это Windows.
                //
                // Winsock отдаёт WSAECONNRESET (10054) следующему
                // `recv`, если на ПРЕДЫДУЩИЙ наш пакет пришёл ICMP
                // «порт недоступен». То есть ошибка описывает уже
                // отправленный пакет, а не состояние сокета.
                //
                // Для пробивания это **штатнейший случай**: пир ещё
                // не слушает, и именно поэтому мы бьём серией. Считать
                // это фатальным значит сдаваться ровно в той
                // ситуации, ради которой модуль написан, — что первая
                // версия и делала, пока тест не поймал.
                //
                // На Unix такого не бывает: там ICMP на неподключённом
                // сокете не всплывает в `recv`.
                Err(ref e) if e.kind() == std::io::ErrorKind::ConnectionReset => {
                    tracing::trace!(attempt, "ICMP «порт недоступен» — пир ещё не слушает");
                    std::thread::sleep(Duration::from_millis(2));
                }
                Err(e) => {
                    return Err(TransportError::Setup(format!("приём при пробивании: {e}")));
                }
            }
        }

        if answered && started.elapsed() >= PUNCH_TIMEOUT {
            break;
        }
    }

    // Возвращаем сокет в блокирующий режим: quinn настроит его под
    // себя, но отдавать ему сокет в чужом состоянии — напрашиваться
    // на разницу поведения между платформами.
    socket
        .set_nonblocking(false)
        .map_err(|e| TransportError::Setup(format!("возврат режима сокета: {e}")))?;

    Ok(if answered {
        PunchOutcome::Opened
    } else {
        tracing::warn!(
            %peer,
            "встречных пакетов не было: NAT может быть симметричным (§5.4)"
        );
        PunchOutcome::NoAnswer
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Два сокета на localhost: пробивание обязано увидеть друг друга.
    ///
    /// NAT здесь нет, и это осознанное ограничение проверки: она
    /// подтверждает механику (пакеты уходят, распознаются, режим
    /// сокета восстанавливается), но НЕ то, ради чего модуль написан.
    /// Настоящее пробивание проверяется только между двумя машинами
    /// за разными роутерами — на localhost воспроизводится не то
    /// состояние (находки 32, 59).
    #[test]
    fn two_sockets_see_each_other() {
        let a = UdpSocket::bind("127.0.0.1:0").expect("сокет A");
        let b = UdpSocket::bind("127.0.0.1:0").expect("сокет B");
        let addr_a = a.local_addr().expect("адрес A");
        let addr_b = b.local_addr().expect("адрес B");

        let handle = std::thread::spawn(move || punch(&b, addr_a));

        let outcome_a = punch(&a, addr_b).expect("пробивание A");
        let outcome_b = handle.join().expect("поток B").expect("пробивание B");

        assert_eq!(outcome_a, PunchOutcome::Opened);
        assert_eq!(outcome_b, PunchOutcome::Opened);
    }

    #[test]
    fn socket_is_blocking_again_afterwards() {
        // Сокет уходит в quinn, и его состояние — часть контракта.
        // Забыть вернуть режим значит отдать библиотеке сокет, ведущий
        // себя не так, как она ожидает: ошибка проявилась бы далеко
        // от места, где допущена.
        let s = UdpSocket::bind("127.0.0.1:0").expect("сокет");
        // Пир, которого нет: пробивание обязано отработать до конца
        // и вернуть NoAnswer, а не зависнуть.
        let nobody: SocketAddr = "127.0.0.1:1".parse().expect("адрес");

        assert_eq!(
            punch(&s, nobody).expect("пробивание"),
            PunchOutcome::NoAnswer
        );

        // Блокирующий режим проверяется поведением, а не флагом:
        // флага у стандартного сокета не спросить.
        s.set_read_timeout(Some(Duration::from_millis(50)))
            .expect("таймаут");
        let mut buf = [0u8; 8];
        let err = s.recv_from(&mut buf).expect_err("ничего не придёт");
        assert!(
            matches!(
                err.kind(),
                std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
            ),
            "блокирующий сокет с таймаутом обязан ждать, а не отвечать сразу: {err:?}"
        );
    }

    #[test]
    fn punch_packet_is_distinguishable_from_quic() {
        // Пробивающий пакет прилетает в тот же сокет, где пойдёт QUIC.
        // Если бы он был неотличим от начала рукопожатия, приёмник
        // принял бы его за мусор — или, хуже, за начало сессии.
        //
        // Первый байт QUIC-датаграма несёт форму заголовка в старших
        // битах; наш начинается с ASCII 'B' (0x42), что для long
        // header (бит 0x80) невозможно.
        assert_eq!(PUNCH_MAGIC[0], b'B');
        assert_eq!(PUNCH_MAGIC[0] & 0x80, 0, "не должен выглядеть long header");
        assert_eq!(PUNCH_MAGIC.len(), 8);
    }
}
