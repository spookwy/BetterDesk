//! Ошибки транспорта.
//!
//! Деление по одному признаку: можно ли продолжать сессию. Потеря
//! кадра — штатное событие для видео по unreliable datagrams
//! (CLAUDE.md §5.3), а вот разорванное соединение требует
//! переустановки.

use thiserror::Error;

/// Результат операции транспорта.
pub type Result<T> = std::result::Result<T, TransportError>;

/// Ошибка транспорта.
#[derive(Debug, Error)]
pub enum TransportError {
    /// Соединение закрыто удалённой стороной или потеряно.
    #[error("соединение закрыто")]
    Disconnected,

    /// Очередь отправки переполнена: приёмник не успевает.
    ///
    /// Для видео это сигнал **дропнуть кадр**, а не ждать: устаревший
    /// кадр не нужен (CLAUDE.md §5.3).
    #[error("очередь отправки переполнена ({queued} пакетов)")]
    WouldBlock {
        /// Сколько пакетов уже стоит в очереди.
        queued: usize,
    },

    /// Пакет не прошёл разбор.
    ///
    /// Это данные от постороннего (§8.5.3), поэтому ошибка обязана
    /// быть обычным `Err`, а не паникой.
    #[error("некорректный пакет: {0}")]
    Malformed(&'static str),

    /// Кадр не помещается в заданный лимит фрагментов.
    #[error("кадр {bytes} Б не помещается в {limit} фрагментов")]
    TooLarge {
        /// Размер кадра в байтах.
        bytes: usize,
        /// Предел числа фрагментов на кадр.
        limit: usize,
    },

    /// Не удалось настроить транспорт.
    ///
    /// Генерация сертификата, конфигурация TLS, привязка сокета.
    /// В отличие от [`Self::Disconnected`], это ошибка **до** начала
    /// работы: повторять её бессмысленно, надо чинить окружение.
    #[error("не удалось настроить транспорт: {0}")]
    Setup(String),

    /// Не удалось установить соединение.
    ///
    /// Хост недоступен, порт закрыт, рукопожатие не прошло. Отдельно
    /// от [`Self::Disconnected`]: там сессия была и оборвалась, здесь
    /// её не удалось начать — и пользователю нужны разные сообщения.
    #[error("не удалось соединиться: {0}")]
    Connect(String),

    /// Поток транспорта завершился.
    ///
    /// QUIC работает в отдельном потоке (docs/adr/0002), и его гибель
    /// не видна пайплайну напрямую. Эта ошибка означает, что канал
    /// к нему закрыт: продолжать нельзя, но и молча перестать
    /// работать — тоже.
    #[error("поток транспорта завершился")]
    ThreadGone,

    /// Ошибка ввода-вывода сокета.
    #[error("ошибка ввода-вывода: {0}")]
    Io(#[from] std::io::Error),
}

impl TransportError {
    /// Можно ли продолжать сессию после этой ошибки.
    ///
    /// Соединение считается живым при потерях и переполнении очереди:
    /// это нормальная работа канала, а не сбой.
    pub fn is_recoverable(&self) -> bool {
        match self {
            TransportError::Disconnected => false,
            // Настройка и соединение не восстанавливаются повтором
            // того же вызова: чинить надо окружение или адрес.
            // Поток транспорта, однажды умерев, не воскресает.
            TransportError::Setup(_) | TransportError::Connect(_) | TransportError::ThreadGone => {
                false
            }
            TransportError::WouldBlock { .. }
            | TransportError::Malformed(_)
            | TransportError::TooLarge { .. } => true,
            // Сокет мог быть закрыт, а мог отдать ICMP-отказ на один
            // датаграм. Различить здесь нельзя, поэтому решение
            // принимает вызывающий по своей политике повторов.
            TransportError::Io(_) => true,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn losses_do_not_kill_the_session() {
        assert!(TransportError::WouldBlock { queued: 4 }.is_recoverable());
        assert!(TransportError::Malformed("длина").is_recoverable());
        assert!(!TransportError::Disconnected.is_recoverable());
    }
}
