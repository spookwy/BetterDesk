//! Хранение приватного ключа под защитой ОС (DPAPI).
//!
//! # Зачем отдельный крейт
//!
//! `bd-crypto` объявляет [`KeyStore`] и переносимую файловую
//! реализацию, но живёт под `#![forbid(unsafe_code)]` и обязан
//! собираться под Linux (§4.2.1). DPAPI — это Win32, то есть `unsafe`
//! и зависимость от `windows`.
//!
//! Отсюда шестой крейт с разрешённым `unsafe` (§4.3.1). Он делает
//! ровно одно: заворачивает два вызова crypt32 в безопасный тип. Всё
//! остальное — решение, что и когда хранить, — остаётся в `bd-crypto`,
//! где `unsafe` по-прежнему запрещён.
//!
//! # Что даёт DPAPI и чего не даёт
//!
//! `CryptProtectData` с областью «текущий пользователь» шифрует байты
//! ключом, выведенным из учётных данных пользователя и машины. Файл,
//! скопированный на другой компьютер или открытый другим
//! пользователем, **не расшифруется** — а без DPAPI 32 байта ключа
//! лежали бы открыто, и укравший файл выдал бы свою машину за нашу.
//!
//! Чего это **не** даёт (записано, чтобы не приняли за большее):
//!
//! - защиты от процесса, работающего под тем же пользователем. DPAPI
//!   расшифрует ключ и для него — это его устройство, а не наш
//!   недосмотр. Против локального вредоноса (противник 6 в
//!   docs/security-model.md) помог бы TPM или пароль при каждом
//!   запуске, и оба ломают «скачал и запустил» (§7.1);
//! - защиты от администратора машины, который может олицетворить
//!   пользователя;
//! - переносимости: в этом весь смысл, но у него есть цена — см.
//!   раздел про переустановку ниже.
//!
//! # Что происходит при переустановке Windows
//!
//! Ключ DPAPI пропадает вместе с профилем, и `device.key`
//! расшифровать больше нечем. Это **ожидаемое** поведение, а не сбой:
//! машина честно потеряла свою личность, и все, кто её запомнил,
//! увидят предупреждение о смене ключа (см. `bd_crypto::pinning`).
//!
//! Важно, чтобы это не выглядело как порча файла: причина называется
//! отдельным вариантом ошибки — [`SecretsError::NotOurs`].

#![deny(unsafe_op_in_unsafe_fn)]

#[cfg(windows)]
mod windows_dpapi;

#[cfg(windows)]
pub use windows_dpapi::DpapiKeyStore;

/// Ошибки защищённого хранилища.
#[derive(Debug, thiserror::Error)]
pub enum SecretsError {
    /// Windows отказала в шифровании или расшифровке.
    #[error("DPAPI не смог обработать данные: {0}")]
    Dpapi(String),

    /// Данные зашифрованы не для этого пользователя или машины.
    ///
    /// Отдельно от [`Self::Dpapi`], потому что причина понятна и
    /// объяснима человеку: так выглядит переустановка Windows, смена
    /// пользователя или файл, принесённый с чужого компьютера.
    ///
    /// Без этого различия человек получил бы «ключ повреждён» и пошёл
    /// бы искать сбой диска — то есть правдоподобную неверную причину
    /// (находки 61, 63, 65).
    #[error(
        "ключ зашифрован для другого пользователя или другой машины \
             (так выглядит переустановка Windows или копия чужого файла)"
    )]
    NotOurs,
}

// Под не-Windows крейт пуст, но **собирается**.
//
// Соблазн поставить здесь `compile_error!` велик: «DPAPI не бывает на
// Linux, значит собирать нечего». Но тогда `cargo build --workspace`
// на Linux падал бы целиком — а он там запускается, и не зря: §4.2.1
// требует, чтобы переносимые крейты не обрастали платформенным
// незаметно.
//
// Правильное поведение — пустой крейт: тот, кому нужно хранилище на
// Linux, берёт `bd_crypto::FileKeyStore` и получает ошибку типов,
// а не оборванную сборку всего проекта.

/// Открыть хранилище ключа этой машины, перенеся старый ключ под
/// защиту ОС, если он лежал открытым.
///
/// # Зачем миграция, а не «просто начать шифровать»
///
/// До появления DPAPI ключ лежал в `device.key` открытыми 32 байтами.
/// Начни мы просто писать зашифрованный файл, старый не прочитался бы
/// — и машина **сменила бы личность**: все, кто её запомнил, получили
/// бы предупреждение о подмене (`bd_crypto::pinning`). На ровном
/// месте, из-за обновления программы.
///
/// А после пары ложных тревог человек перестаёт читать настоящие.
/// Поэтому старый ключ читается, перешифровывается и сохраняется под
/// тем же именем — личность сохраняется.
///
/// # Порядок именно такой
///
/// 1. Пробуем прочитать как защищённый (обычный случай после первого
///    запуска новой версии);
/// 2. не вышло — пробуем как открытый и **сразу перешифровываем**;
/// 3. нет ни того ни другого — выпускаем новый.
///
/// Обратный порядок был бы опаснее: файл, зашифрованный DPAPI,
/// случайно разобрать как открытый ключ нельзя (длина другая), а вот
/// молча принять чужой блоб за «повреждённый и требующий замены» —
/// можно, и это стоило бы личности.
#[cfg(windows)]
pub fn open_key_store(path: std::path::PathBuf) -> Box<dyn bd_crypto::KeyStore> {
    use bd_crypto::KeyStore as _;

    let protected = DpapiKeyStore::new(path.clone());

    // Уже защищён или отсутствует — делать нечего.
    match protected.load() {
        Ok(Some(_)) | Ok(None) => return Box::new(protected),
        Err(_) => {}
    }

    // Не прочитался как защищённый. Возможно, это старый открытый
    // ключ — пробуем и переносим.
    let plain = bd_crypto::FileKeyStore::new(path);
    match plain.load() {
        Ok(Some(identity)) => match protected.save(&identity) {
            Ok(()) => {
                tracing::info!("ключ устройства перенесён под защиту DPAPI");
                Box::new(protected)
            }
            Err(e) => {
                // Перенести не вышло — **возвращаем открытое
                // хранилище**, а не защищённое.
                //
                // Это не мелочь: вернув `protected`, мы отдали бы
                // хранилище, которое лежащий на диске файл прочитать
                // не может, — и следующий `load_or_create` выпустил бы
                // НОВЫЙ ключ. То есть неудавшееся улучшение стоило бы
                // машине личности и подняло бы ложную тревогу о
                // подмене у всех, кто её запомнил.
                //
                // Первая версия этой функции так и делала: в
                // комментарии стояло «работаем с тем, что есть», а код
                // возвращал защищённое. Ровно находка 31 — у записи
                // «вызывающий обязан» не оказалось исполнителя.
                tracing::warn!(
                    "не удалось защитить ключ через DPAPI: {e}; \
                     работаю с незашифрованным ключом"
                );
                Box::new(plain)
            }
        },
        // Ни защищённый, ни открытый. Пусть вызывающий получит
        // честную ошибку от `load_or_create` защищённого хранилища —
        // она назовёт настоящую причину (чужая машина, переустановка).
        _ => Box::new(protected),
    }
}

#[cfg(all(test, windows))]
mod migration_tests {
    use super::*;
    use bd_crypto::{DeviceIdentity, FileKeyStore, KeyStore as _};

    fn temp_path(name: &str) -> std::path::PathBuf {
        let mut path = std::env::temp_dir();
        path.push(format!("bd-migration-{name}-{}", std::process::id()));
        path.push("device.key");
        path
    }

    fn cleanup(path: &std::path::Path) {
        if let Some(parent) = path.parent() {
            let _ = std::fs::remove_dir_all(parent);
        }
    }

    /// **Главный тест: миграция не меняет личность машины.**
    ///
    /// Если бы старый открытый ключ просто не читался, `load_or_create`
    /// выпустил бы новый — и все, кто запомнил эту машину, увидели бы
    /// предупреждение о подмене после обычного обновления программы.
    #[test]
    fn plain_key_survives_migration() {
        let path = temp_path("survives");
        cleanup(&path);

        // Было: ключ лежит открытым (так работали прошлые версии).
        let before = DeviceIdentity::generate().expect("генерация");
        FileKeyStore::new(&path).save(&before).expect("старый ключ");

        // Стало: открываем через миграцию.
        let migrated = open_key_store(path.clone())
            .load_or_create()
            .expect("после миграции");

        assert_eq!(
            before.public(),
            migrated.public(),
            "личность машины изменилась при переносе ключа"
        );

        cleanup(&path);
    }

    /// После миграции файл на диске больше не содержит ключа открытым:
    /// иначе перенос был бы бессмысленным.
    #[test]
    fn migration_actually_encrypts_the_file() {
        let path = temp_path("encrypts");
        cleanup(&path);

        let before = DeviceIdentity::generate().expect("генерация");
        let raw = before.to_secret_bytes();
        FileKeyStore::new(&path).save(&before).expect("старый ключ");

        let _ = open_key_store(path.clone())
            .load_or_create()
            .expect("миграция");

        let on_disk = std::fs::read(&path).expect("чтение");
        assert!(
            !on_disk.windows(raw.len()).any(|w| w == raw),
            "после миграции ключ всё ещё лежит открытым"
        );

        cleanup(&path);
    }

    /// Повторный запуск ничего не ломает: ключ уже защищён, миграция
    /// должна пройти мимо и не тронуть файл.
    #[test]
    fn second_run_is_stable() {
        let path = temp_path("stable");
        cleanup(&path);

        let first = open_key_store(path.clone())
            .load_or_create()
            .expect("первый запуск");
        let second = open_key_store(path.clone())
            .load_or_create()
            .expect("второй запуск");

        assert_eq!(first.public(), second.public());
        cleanup(&path);
    }

    /// Чистая машина: ключа нет вовсе — выпускается новый и сразу
    /// защищённым, а не открытым.
    #[test]
    fn fresh_machine_gets_protected_key() {
        let path = temp_path("fresh");
        cleanup(&path);

        let identity = open_key_store(path.clone())
            .load_or_create()
            .expect("новый ключ");
        let raw = identity.to_secret_bytes();

        let on_disk = std::fs::read(&path).expect("чтение");
        assert!(
            !on_disk.windows(raw.len()).any(|w| w == raw),
            "новый ключ сохранён открытым"
        );

        cleanup(&path);
    }
}
