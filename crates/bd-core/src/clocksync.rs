//! Оценка смещения часов между двумя машинами.
//!
//! # Зачем это нужно
//!
//! Кадр несёт метку времени захвата (§4.5), но она снята **часами
//! отправителя**. Вычесть её из своего времени напрямую нельзя:
//! получится разница часов, а не задержка. У двух машин эпохи
//! начинаются в разные моменты, и расхождение — это не миллисекунды,
//! а секунды или больше.
//!
//! Без поправки glass-to-glass между машинами не измерить вовсе
//! (CLAUDE.md §0.1, находка 40).
//!
//! # Как оценивается смещение
//!
//! Метод простой и достаточный для нашей задачи: **минимум наблюдённой
//! разницы**.
//!
//! Для каждого кадра считается `свои_часы_при_получении −
//! чужие_часы_при_захвате`. В этой разнице сидят две составляющие:
//! постоянное смещение часов и переменная задержка доставки. Задержка
//! всегда положительна и всегда добавляется — значит, **минимум по
//! множеству кадров ближе всего к чистому смещению**, а превышение
//! над минимумом и есть задержка.
//!
//! Точность метода ограничена самой быстрой доставкой за окно
//! наблюдения: если ни один кадр не пришёл мгновенно, оценка смещения
//! завышена ровно на минимальную задержку, а измеренные задержки
//! соответственно занижены. Для LAN, где минимум близок к нулю, это
//! доли миллисекунды.
//!
//! # Чего этот метод не делает
//!
//! Не корректирует **дрейф**: часы двух машин идут с чуть разной
//! скоростью, и за часы работы оценка уплывёт. Лечится тем, что
//! минимум берётся по скользящему окну, а не за всё время: старые
//! наблюдения выпадают, и оценка следует за дрейфом.
//!
//! Не заменяет NTP и не претендует на абсолютную точность. Задача
//! здесь — измерять **задержку**, а для неё важна не абсолютная
//! разница часов, а её постоянство в пределах окна.

use crate::time::Timestamp;

/// Сколько наблюдений держать в окне.
///
/// При 60 fps это около четырёх секунд. Достаточно, чтобы в окно
/// попал хотя бы один быстро доставленный кадр, и достаточно мало,
/// чтобы оценка успевала за дрейфом часов.
const WINDOW: usize = 256;

/// Оценка смещения часов удалённой стороны относительно наших.
///
/// Смещение хранится со знаком: положительное означает, что часы
/// отправителя идут впереди наших.
#[derive(Debug, Clone)]
pub struct ClockSync {
    /// Наблюдения `наши_часы − чужие_часы`, в микросекундах.
    ///
    /// Знаковые: часы отправителя могут идти как впереди, так и
    /// позади наших, и оба случая штатны.
    samples: std::collections::VecDeque<i64>,
    /// Текущая оценка смещения, микросекунды.
    offset_micros: i64,
    /// Сколько наблюдений учтено за всё время.
    total: u64,
}

impl Default for ClockSync {
    fn default() -> Self {
        Self::new()
    }
}

impl ClockSync {
    /// Новая оценка: наблюдений пока нет.
    pub fn new() -> Self {
        Self {
            samples: std::collections::VecDeque::with_capacity(WINDOW),
            offset_micros: 0,
            total: 0,
        }
    }

    /// Учесть кадр: он был захвачен тогда-то по чужим часам и получен
    /// тогда-то по нашим.
    ///
    /// Возвращает оценку задержки доставки этого кадра — то есть
    /// разницу за вычетом смещения часов. Отрицательные значения
    /// зажимаются в ноль: задержка не бывает меньше нуля, а
    /// отрицательная означает лишь, что этот кадр пришёл быстрее
    /// всех прежних и сам стал новым минимумом.
    pub fn observe(&mut self, captured_remote_micros: u64, received_local: Timestamp) -> u64 {
        let diff = received_local.as_micros() as i64 - captured_remote_micros as i64;

        self.samples.push_back(diff);
        if self.samples.len() > WINDOW {
            self.samples.pop_front();
        }
        self.total += 1;

        // Минимум по окну — лучшая доступная оценка смещения:
        // задержка всегда положительна, значит наименьшая разница
        // содержит наименьшую задержку.
        self.offset_micros = self.samples.iter().copied().min().unwrap_or(0);

        (diff - self.offset_micros).max(0) as u64
    }

    /// Текущая оценка смещения часов, микросекунды.
    ///
    /// Положительное значение означает, что часы отправителя идут
    /// впереди наших.
    pub fn offset_micros(&self) -> i64 {
        self.offset_micros
    }

    /// Есть ли уже осмысленная оценка.
    ///
    /// Пока наблюдений мало, минимум может оказаться далеко от истины
    /// — и вычисленные по нему задержки будут завышены. Вызывающий
    /// должен уметь дождаться, а не показывать заведомо неверное.
    pub fn is_settled(&self) -> bool {
        // Тридцати кадров (полсекунды при 60 fps) хватает, чтобы в
        // окно попал хотя бы один кадр без задержки очереди.
        self.total >= 30
    }

    /// Сколько наблюдений учтено.
    pub fn samples(&self) -> u64 {
        self.total
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Смоделировать поток кадров с заданным смещением часов и
    /// задержками, вернув измеренные задержки.
    fn run(offset_micros: i64, delays: &[u64]) -> (ClockSync, Vec<u64>) {
        let mut sync = ClockSync::new();
        let mut measured = Vec::new();

        for (index, delay) in delays.iter().enumerate() {
            // Кадр захвачен по чужим часам в момент `index * 16 мс`.
            let captured_remote = (index as u64) * 16_000;
            // Наши часы: чужие минус смещение, плюс задержка доставки.
            let received_local = (captured_remote as i64 - offset_micros) as u64 + delay;
            measured.push(sync.observe(captured_remote, Timestamp::from_micros(received_local)));
        }

        (sync, measured)
    }

    #[test]
    fn constant_offset_is_removed() {
        // Часы отправителя на 5 секунд впереди, задержка постоянная
        // 3 мс. Без поправки «задержка» вышла бы около −5 секунд.
        let (sync, measured) = run(5_000_000, &[3_000; 50]);

        assert!(sync.is_settled());
        // Постоянная задержка неотличима от смещения — это
        // принципиальное ограничение метода, и оно должно быть видно
        // в тесте, а не всплыть на живом канале.
        assert!(
            measured.iter().all(|&d| d == 0),
            "при постоянной задержке метод даёт нули: {:?}",
            &measured[..5]
        );
    }

    #[test]
    fn variable_delay_is_measured_above_the_minimum() {
        // Минимум 2 мс, всплески до 10 мс. Метод обязан показать
        // превышение над минимумом, а не абсолютную задержку.
        let delays = [2_000u64, 5_000, 10_000, 2_000, 7_000, 3_000];
        let (_, measured) = run(1_000_000, &delays);

        // Первый кадр всегда даёт ноль: он сам себе минимум.
        assert_eq!(measured[0], 0);
        // Кадр с задержкой 10 мс при минимуме 2 мс — превышение 8 мс.
        assert_eq!(measured[2], 8_000, "измеренные: {measured:?}");
        assert_eq!(measured[4], 5_000);
    }

    #[test]
    fn negative_offset_works_too() {
        // Часы отправителя ПОЗАДИ наших. Знаковая арифметика должна
        // это выдержать: беззнаковая дала бы переполнение.
        let (sync, measured) = run(-3_000_000, &[1_000, 4_000, 1_000]);
        assert!(
            sync.offset_micros() > 0,
            "смещение: {}",
            sync.offset_micros()
        );
        assert_eq!(measured[1], 3_000);
    }

    #[test]
    fn delay_is_never_negative() {
        // Кадр, пришедший быстрее всех прежних, становится новым
        // минимумом. Его собственная задержка при этом — ноль,
        // а не отрицательное число.
        let (_, measured) = run(0, &[10_000, 8_000, 5_000, 1_000]);
        assert!(
            measured.iter().all(|&d| d < u64::MAX / 2),
            "отрицательная задержка переполнилась бы: {measured:?}"
        );
        assert_eq!(measured[3], 0, "самый быстрый кадр задаёт новый минимум");
    }

    #[test]
    fn window_forgets_old_samples() {
        // Оценка обязана следовать за дрейфом часов. Если минимум
        // берётся за всё время, устаревшее наблюдение навсегда
        // испортит все последующие измерения.
        let mut sync = ClockSync::new();

        // Один очень «быстрый» кадр в начале.
        sync.observe(0, Timestamp::from_micros(0));
        let early_offset = sync.offset_micros();

        // Затем много кадров со сместившимися часами.
        for i in 1..=(WINDOW as u64 + 50) {
            sync.observe(i * 16_000, Timestamp::from_micros(i * 16_000 + 100_000));
        }

        assert_ne!(
            sync.offset_micros(),
            early_offset,
            "старое наблюдение не выпало из окна — оценка не следует за дрейфом"
        );
    }

    #[test]
    fn not_settled_until_enough_samples() {
        // Показывать задержку по двум наблюдениям — значит показывать
        // выдумку: минимум ещё не найден.
        let mut sync = ClockSync::new();
        for i in 0..5u64 {
            sync.observe(i * 16_000, Timestamp::from_micros(i * 16_000 + 3_000));
            assert!(!sync.is_settled(), "рано считать оценку установившейся");
        }
        for i in 5..40u64 {
            sync.observe(i * 16_000, Timestamp::from_micros(i * 16_000 + 3_000));
        }
        assert!(sync.is_settled());
    }

    #[test]
    fn empty_sync_reports_zero_offset() {
        let sync = ClockSync::new();
        assert_eq!(sync.offset_micros(), 0);
        assert_eq!(sync.samples(), 0);
        assert!(!sync.is_settled());
    }
}
