//! Определение своего внешнего UDP-адреса (STUN).
//!
//! # Зачем это понадобилось отдельно от сигналинга
//!
//! Сигналинг ходит по WebSocket, то есть по TCP, и сервер видит
//! адрес **этого** соединения: внешний IP плюс внешний **TCP**-порт.
//! Долгое время он его и отдавал сторонам как адрес для пробивания
//! NAT — и это работало на одной машине, где обе стороны за одним
//! NAT и обмениваются локальными адресами.
//!
//! Через интернет это не работает, и первый же прогон между двумя
//! машинами провалился (находка 65). Пробивание и QUIC идут по
//! **UDP, с другого сокета**, а NAT выдаёт ему собственный внешний
//! порт, никак не связанный с TCP. Стороны честно били — каждая в
//! TCP-порт собеседника, то есть в никуда.
//!
//! Видно это было прямо в логах хоста:
//!
//! ```text
//! Внешний адрес: 91.211.134.184:34097   <- порт TCP-соединения
//! ... хост ждёт подключения local=0.0.0.0:7000   <- порт UDP
//! ```
//!
//! Внешний UDP-порт нельзя вычислить или угадать: его знает только
//! NAT, и узнать можно единственным способом — послать пакет
//! наружу с того самого сокета и спросить, каким его увидели.
//! Это и есть STUN.
//!
//! # Почему свой протокол, а не RFC 5389
//!
//! Настоящий STUN — это заголовки с magic cookie, атрибуты типа
//! XOR-MAPPED-ADDRESS, транзакционные идентификаторы. Всё это нужно
//! для совместимости с чужими серверами и для работы через
//! посредников, которые переписывают адреса.
//!
//! Нам нужен один вопрос своему же серверу и один ответ. Свой
//! формат — три строки кода вместо разбора чужого бинарного
//! протокола, и его видно глазами в дампе трафика, что для отладки
//! между двумя машинами через интернет дороже совместимости.
//!
//! Если понадобятся публичные STUN-серверы (например, когда наш
//! недоступен), RFC-совместимый клиент добавится рядом — формат
//! здесь опознаётся по префиксу и с чужим не столкнётся.

use core::fmt;

/// Запрос: «каким ты меня видишь».
///
/// Восемь байт с явной сигнатурой, как у пробивающего пакета: он
/// прилетает на тот же UDP-порт, где живёт сигналинг, и сервер
/// обязан отличить его от чего угодно другого.
pub const STUN_REQUEST: &[u8] = b"BDSTUNQ\x01";

/// Префикс ответа. Дальше идёт адрес текстом.
pub const STUN_REPLY_PREFIX: &[u8] = b"BDSTUNR\x01";

/// Предел длины ответа.
///
/// Недоверенные данные: ответ приходит из сети, и отвечать может
/// кто угодно, а не только наш сервер. Без предела строка от
/// постороннего заставила бы разбирать что попало.
///
/// 64 байта хватает с запасом: самый длинный адрес IPv6 с портом
/// укладывается в 54 символа.
pub const STUN_MAX_REPLY: usize = 64;

/// Собрать ответ на STUN-запрос.
///
/// `seen` — адрес, с которого пришёл запрос, как его видит сервер.
pub fn encode_reply(seen: &impl fmt::Display) -> Vec<u8> {
    let mut out = Vec::with_capacity(STUN_MAX_REPLY);
    out.extend_from_slice(STUN_REPLY_PREFIX);
    out.extend_from_slice(seen.to_string().as_bytes());
    out
}

/// Разобрать ответ и вернуть адрес текстом.
///
/// Возвращает `None`, если это не наш ответ или он повреждён.
/// Разбирать дальше — задача вызывающего: `bd-core` не знает про
/// `SocketAddr` из стандартной библиотеки в no_std-совместимой
/// части, а проверка формата адреса всё равно нужна на месте.
pub fn decode_reply(datagram: &[u8]) -> Option<&str> {
    if datagram.len() > STUN_MAX_REPLY {
        return None;
    }
    let rest = datagram.strip_prefix(STUN_REPLY_PREFIX)?;
    // Адрес — печатаемый ASCII. Проверка нужна: строка попадёт в
    // лог и в сообщения человеку, а управляющие символы там ни к
    // чему (§8.5 — недоверенный ввод).
    let text = core::str::from_utf8(rest).ok()?;
    if text.is_empty() || !text.bytes().all(|b| b.is_ascii_graphic()) {
        return None;
    }
    Some(text)
}

/// Похож ли датаграм на STUN-запрос.
pub fn is_request(datagram: &[u8]) -> bool {
    datagram == STUN_REQUEST
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reply_roundtrip() {
        let reply = encode_reply(&"91.211.134.184:34097");
        assert_eq!(decode_reply(&reply), Some("91.211.134.184:34097"));
    }

    #[test]
    fn request_is_recognised() {
        assert!(is_request(STUN_REQUEST));
        assert!(!is_request(b"BDPUNCH\x01"));
        assert!(!is_request(b""));
    }

    #[test]
    fn rejects_foreign_and_broken_datagrams() {
        // Проверка обязана уметь отвергать — иначе она ничего не
        // значит (находка 4).
        assert_eq!(decode_reply(b"nonsense"), None);
        assert_eq!(decode_reply(b""), None);
        // Наш префикс, но пустой адрес.
        assert_eq!(decode_reply(STUN_REPLY_PREFIX), None);
        // Слишком длинный ответ: попытка заставить нас разбирать
        // мусор произвольной длины.
        let mut huge = STUN_REPLY_PREFIX.to_vec();
        huge.extend_from_slice(&[b'1'; STUN_MAX_REPLY]);
        assert_eq!(decode_reply(&huge), None);
        // Управляющие символы в адресе.
        let mut bad = STUN_REPLY_PREFIX.to_vec();
        bad.extend_from_slice(b"1.2.3.4:80\n\x07");
        assert_eq!(decode_reply(&bad), None);
    }

    #[test]
    fn punch_and_stun_do_not_collide() {
        // Оба пакета прилетают на UDP-порты BetterDesk, и спутать их
        // нельзя: пробивающий уйдёт в разбор адреса, а STUN-ответ —
        // в сборщик кадров.
        assert_ne!(STUN_REQUEST, b"BDPUNCH\x01");
        assert_ne!(STUN_REPLY_PREFIX, b"BDPUNCH\x01");
    }
}
