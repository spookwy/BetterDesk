//! Идентификатор устройства: девять цифр, которые человек диктует
//! голосом.
//!
//! # Чем ID является и чем НЕ является
//!
//! ID — **удобное имя**, а не средство аутентификации (CLAUDE.md
//! §7.3). Знание чужого ID не даёт никаких прав: подключение требует
//! пароля, а личность устройства даёт ключ Ed25519 (этап 5).
//!
//! Это важно записать здесь, потому что девятизначное число легко
//! принять за секрет. Оно печатается на экране крупным шрифтом
//! ровно затем, чтобы его прочитали вслух.
//!
//! # Почему девять цифр
//!
//! Столько же у AnyDesk, и причина практическая: девять цифр
//! диктуются одним дыханием группами по три, а вероятность угадать
//! чужой ID при 900 миллионах вариантов не имеет значения — угадав,
//! атакующий упрётся в пароль.

use core::fmt;

/// Идентификатор устройства.
///
/// Внутри — число от 100 000 000 до 999 999 999. Ведущий ноль
/// исключён намеренно: он теряется везде, где строку «умно» приводят
/// к числу, и человек начинает диктовать ID, которого не существует.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct DeviceId(u32);

/// Наименьший допустимый ID (первая цифра не ноль).
const MIN: u32 = 100_000_000;
/// Наибольший допустимый ID.
const MAX: u32 = 999_999_999;

impl DeviceId {
    /// Собрать ID из числа.
    ///
    /// `None`, если число вне диапазона девятизначных.
    pub const fn from_u32(value: u32) -> Option<Self> {
        if value >= MIN && value <= MAX {
            Some(Self(value))
        } else {
            None
        }
    }

    /// Вывести ID из произвольного посева — например, из имени
    /// машины и пользователя.
    ///
    /// # Это временное решение, и оно помечено таковым
    ///
    /// Настоящий ID выдаёт сигналинг при регистрации (§5.4): только
    /// сервер может гарантировать, что номер никем не занят. Здесь
    /// ID выводится локально — он устойчив между запусками, но
    /// **никем не подтверждён**, и двум разным машинам может
    /// достаться один номер.
    ///
    /// Вероятность такого совпадения — не абстракция: при 900 млн
    /// вариантов и тысяче машин это парадокс дней рождения, то есть
    /// примерно один шанс из тысячи восьмисот. Мало для теста,
    /// недопустимо для продукта.
    pub fn derive(seed: &str) -> Self {
        // FNV-1a: короткая, детерминированная, без зависимостей.
        // Криптостойкость здесь не нужна и не подразумевается —
        // ID ничего не защищает.
        let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
        for byte in seed.as_bytes() {
            hash ^= u64::from(*byte);
            hash = hash.wrapping_mul(0x100_0000_01b3);
        }

        let span = u64::from(MAX - MIN) + 1;
        Self(MIN + (hash % span) as u32)
    }

    /// Разобрать ID, введённый человеком.
    ///
    /// Пробелы, дефисы и точки игнорируются: человек копирует ID
    /// из чата, где он мог быть записан как угодно. Отказывать
    /// из-за разделителя — значит заставлять его чистить строку
    /// вручную, хотя намерение очевидно.
    pub fn parse(input: &str) -> Option<Self> {
        let mut digits = 0u32;
        let mut count = 0u32;

        for ch in input.chars() {
            match ch {
                '0'..='9' => {
                    count += 1;
                    // Больше девяти цифр — это не ID, а опечатка.
                    // Молча брать первые девять нельзя: человек
                    // подключится не туда, куда собирался.
                    if count > 9 {
                        return None;
                    }
                    digits = digits * 10 + (ch as u32 - '0' as u32);
                }
                // Разделители, которыми ID записывают в переписке.
                ' ' | '-' | '.' | '\u{00A0}' | '\t' => {}
                // Всё прочее — признак, что это вообще не ID.
                _ => return None,
            }
        }

        if count != 9 {
            return None;
        }
        Self::from_u32(digits)
    }

    /// Число, лежащее внутри.
    pub const fn as_u32(self) -> u32 {
        self.0
    }

    /// Строка без разделителей: `418207356`.
    ///
    /// Такой вид уходит в сеть — там группировка лишний байт и лишний
    /// повод для расхождения форматов между сторонами.
    pub fn to_compact(self) -> String {
        self.0.to_string()
    }
}

/// Человеку ID показывается группами по три: `418 207 356`.
///
/// Так его читают вслух и так переписывают, и группировка заметно
/// снижает число ошибок при диктовке.
impl fmt::Display for DeviceId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = self.0.to_string();
        write!(f, "{} {} {}", &s[0..3], &s[3..6], &s[6..9])
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn derived_id_is_nine_digits() {
        for seed in ["", "a", "МАШИНА\u{1}пользователь", "x".repeat(500).as_str()]
        {
            let id = DeviceId::derive(seed);
            let n = id.as_u32();
            assert!((MIN..=MAX).contains(&n), "посев {seed:?} дал {n}");
            assert_eq!(id.to_compact().len(), 9);
        }
    }

    #[test]
    fn derived_id_is_stable() {
        // Человек, увидевший свой ID вчера, обязан увидеть тот же
        // сегодня: иначе записи о нём у собеседника мертвы.
        assert_eq!(DeviceId::derive("машина"), DeviceId::derive("машина"));
        assert_ne!(DeviceId::derive("машина"), DeviceId::derive("другая"));
    }

    #[test]
    fn display_groups_by_three() {
        let id = DeviceId::from_u32(418_207_356).expect("валидный ID");
        assert_eq!(id.to_string(), "418 207 356");
        assert_eq!(id.to_compact(), "418207356");
    }

    #[test]
    fn parse_accepts_what_people_actually_type() {
        let want = DeviceId::from_u32(418_207_356).expect("валидный ID");
        // Все эти виды встречаются при копировании из переписки.
        for input in [
            "418207356",
            "418 207 356",
            "418-207-356",
            "418.207.356",
            " 418 207 356 ",
        ] {
            assert_eq!(
                DeviceId::parse(input),
                Some(want),
                "не разобрано: {input:?}"
            );
        }
    }

    #[test]
    fn parse_rejects_what_is_not_an_id() {
        // Тест проверен на способность провалиться: без проверки
        // count != 9 первые три случая проходят.
        for input in [
            "",           // пусто
            "418207",     // мало цифр
            "4182073567", // много цифр
            "41820735a",  // буква
            "018207356",  // ведущий ноль — такого ID не бывает
            "418 207 35", // недобор с разделителями
        ] {
            assert_eq!(DeviceId::parse(input), None, "принято зря: {input:?}");
        }
    }

    #[test]
    fn parse_rejects_overflow_without_panicking() {
        // Недоверенный ввод: длинная строка цифр не должна ни
        // переполнить u32 с паникой, ни быть молча обрезанной
        // до первых девяти (§4.3.5 — парсеры сетевых данных).
        assert_eq!(DeviceId::parse(&"9".repeat(40)), None);
    }

    #[test]
    fn from_u32_guards_the_range() {
        assert!(DeviceId::from_u32(99_999_999).is_none(), "восемь цифр");
        assert!(DeviceId::from_u32(1_000_000_000).is_none(), "десять цифр");
        assert!(DeviceId::from_u32(MIN).is_some());
        assert!(DeviceId::from_u32(MAX).is_some());
    }
}
