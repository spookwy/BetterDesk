//! Пароль сессии: генерация, хеширование, проверка.
//!
//! # Что защищает и от чего
//!
//! До этого модуля хост, зарегистрированный на публичном сигналинге,
//! отдавал экран **любому, кто угадает девять цифр**. ID — это удобное
//! имя, а не секрет (§7.3): он короткий, печатается на экране и
//! диктуется вслух. Перебирать его дёшево.
//!
//! Пароль закрывает именно это: знать ID недостаточно, нужно ещё
//! знать секрет, который человек за хостом сообщил сам.
//!
//! # Чего он НЕ защищает
//!
//! Подмены сигналинга. Сервер может свести клиента не с тем хостом,
//! и пароль этого не заметит — он проверяет знание секрета, а не то,
//! с кем мы разговариваем. Против подмены нужен пиннинг ключей
//! устройств (§7.3, этап 5), и до него сервер остаётся недоверенным.
//!
//! Записано прямо, потому что соблазн счесть «пароль есть — значит
//! безопасно» велик, а это разные свойства.
//!
//! # Почему Argon2id, а не что-то быстрое
//!
//! Пароль короткий (шесть цифр — миллион вариантов), и быстрая
//! хеш-функция позволила бы перебрать его за секунды, получив хеш.
//! Argon2id намеренно медленный и требует памяти, поэтому перебор
//! стоит дорого даже на видеокарте. Это победитель Password Hashing
//! Competition и текущая рекомендация OWASP.
//!
//! Своя криптография здесь не пишется (§8.1) — только сборка
//! проверенных примитивов.

use argon2::password_hash::{PasswordHasher, PasswordVerifier};
use argon2::Argon2;
use rand::{rng, RngExt};

/// Длина одноразового пароля в цифрах.
///
/// Шесть — как у AnyDesk и у кодов двухфакторной аутентификации.
/// Компромисс между «человек продиктует по телефону не сбившись» и
/// «перебрать нельзя».
///
/// Миллион вариантов сам по себе невелик, и защищает не длина, а то,
/// что пароль **одноразовый и живёт минуты**: он меняется при каждом
/// запуске хоста, а неудачные попытки замедляются (см.
/// [`SessionPassword::verify`]).
const PASSWORD_DIGITS: usize = 6;

/// Ошибка при работе с паролем.
#[derive(Debug, thiserror::Error)]
pub enum PasswordError {
    /// Не удалось захешировать или проверить.
    ///
    /// Текст из библиотеки наружу **не отдаётся**: он может
    /// различаться для разных причин отказа, а это подсказка тому,
    /// кто перебирает. Наружу — одинаковое «не сошлось».
    #[error("проверка пароля не удалась")]
    Failed,
}

/// Одноразовый пароль сессии.
///
/// Хранит **хеш**, а не сам пароль: даже дамп памяти хоста не выдаст
/// секрет в открытом виде. Открытый текст живёт ровно столько,
/// сколько нужно, чтобы показать его человеку.
#[derive(Debug, Clone)]
pub struct SessionPassword {
    hash: String,
}

impl SessionPassword {
    /// Сгенерировать новый случайный пароль.
    ///
    /// Возвращает пару: сам пароль (его надо показать человеку) и
    /// объект для проверки. Пароль отдаётся отдельным значением
    /// намеренно — так видно, что он покидает модуль ровно один раз
    /// и осознанно.
    pub fn generate() -> Result<(String, Self), PasswordError> {
        let mut generator = rng();
        // Криптографический генератор, а не `%` от времени: пароль,
        // который можно предсказать по моменту запуска, не пароль.
        let plain: String = (0..PASSWORD_DIGITS)
            .map(|_| char::from(b'0' + generator.random_range(0..10u8)))
            .collect();

        let this = Self::from_plaintext(&plain)?;
        Ok((plain, this))
    }

    /// Захешировать заданный пароль.
    ///
    /// Нужен для постоянного пароля необслуживаемого доступа (§7.3),
    /// который человек задаёт сам.
    pub fn from_plaintext(plain: &str) -> Result<Self, PasswordError> {
        // Соль генерируется самой библиотекой и своя на каждый хеш:
        // без неё одинаковые пароли дают одинаковые хеши, и таблица
        // заранее посчитанных значений вскрыла бы их все разом.
        let hash = Argon2::default()
            .hash_password(plain.as_bytes())
            .map_err(|_| PasswordError::Failed)?
            .to_string();
        Ok(Self { hash })
    }

    /// Проверить введённый пароль.
    ///
    /// # Постоянство времени
    ///
    /// Сравнение внутри `argon2` не зависит от того, где именно
    /// разошлись хеши: иначе время ответа выдавало бы, сколько
    /// символов угадано, и перебор из миллиона вариантов свёлся бы к
    /// шести перебором по одному символу.
    ///
    /// Мы полагаемся на библиотеку, а не сравниваем строки сами —
    /// ровно потому, что наивное `==` эту утечку и создаёт.
    pub fn verify(&self, attempt: &str) -> bool {
        let Ok(parsed) = argon2::password_hash::phc::PasswordHash::new(&self.hash) else {
            // Хеш испорчен — считаем, что не сошлось. Пропустить
            // вместо отказа здесь было бы худшим из возможных
            // решений: сбой превратился бы в отсутствие защиты.
            return false;
        };
        Argon2::default()
            .verify_password(attempt.as_bytes(), &parsed)
            .is_ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_password_verifies() {
        let (plain, password) = SessionPassword::generate().expect("генерация");
        assert!(password.verify(&plain), "свой же пароль обязан подойти");
    }

    #[test]
    fn wrong_password_is_rejected() {
        // Проверка, которая умеет провалиться (находка 4): без неё
        // `verify`, всегда отвечающий `true`, прошёл бы первый тест.
        let (plain, password) = SessionPassword::generate().expect("генерация");
        assert!(!password.verify("000000"), "чужой пароль не должен подойти");
        assert!(!password.verify(""), "пустой пароль не должен подойти");
        assert!(
            !password.verify(&format!("{plain}1")),
            "пароль с лишним символом не должен подойти"
        );
    }

    #[test]
    fn password_is_six_digits() {
        let (plain, _) = SessionPassword::generate().expect("генерация");
        assert_eq!(plain.len(), PASSWORD_DIGITS);
        assert!(
            plain.chars().all(|c| c.is_ascii_digit()),
            "пароль диктуют по телефону — только цифры: {plain}"
        );
    }

    #[test]
    fn passwords_differ_between_runs() {
        // Предсказуемый пароль не пароль. Десять подряд одинаковых
        // означали бы, что генератор не работает вовсе.
        let mut seen = std::collections::HashSet::new();
        for _ in 0..10 {
            let (plain, _) = SessionPassword::generate().expect("генерация");
            seen.insert(plain);
        }
        assert!(
            seen.len() > 1,
            "генератор выдаёт один и тот же пароль — это не случайность"
        );
    }

    #[test]
    fn hash_does_not_contain_the_password() {
        // Хеш попадает в логи и дампы. Пароль в нём в открытом виде
        // сделал бы всю схему бессмысленной.
        let (plain, password) = SessionPassword::generate().expect("генерация");
        assert!(
            !password.hash.contains(&plain),
            "пароль виден в хеше открытым текстом"
        );
    }

    #[test]
    fn same_password_gives_different_hashes() {
        // Своя соль на каждый хеш: одинаковые хеши у одинаковых
        // паролей позволили бы вскрыть их таблицей заранее
        // посчитанных значений.
        let a = SessionPassword::from_plaintext("123456").expect("хеш");
        let b = SessionPassword::from_plaintext("123456").expect("хеш");
        assert_ne!(a.hash, b.hash, "соль не применяется");
        // При этом оба обязаны проверяться.
        assert!(a.verify("123456"));
        assert!(b.verify("123456"));
    }

    #[test]
    fn corrupted_hash_rejects_everything() {
        // Сбой не должен превращаться в отсутствие защиты.
        let password = SessionPassword {
            hash: "мусор, а не хеш".into(),
        };
        assert!(!password.verify("123456"));
        assert!(!password.verify(""));
    }
}
