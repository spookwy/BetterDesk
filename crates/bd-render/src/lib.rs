//! Рендер: D3D11 swapchain, вывод NV12, оверлей статистики.
//!
//! # Что здесь критично для задержки
//!
//! Три решения, каждое ценой в кадры (docs/latency-budget.md §3):
//!
//! - `SetMaximumFrameLatency(1)` — по умолчанию DXGI держит очередь
//!   из трёх кадров, это +33–50 мс на ровном месте;
//! - `Present(0, ...)` без VSync — ожидание синхронизации добавляет
//!   до 16.6 мс, а тиринг при удалённой работе меньшее зло;
//! - конверсия NV12→RGB шейдером — на CPU она стоила бы копии кадра
//!   в системную память и обратно (CLAUDE.md §4.2.3).
//!
//! # Границы
//!
//! Видео **никогда** не рендерится в webview (CLAUDE.md §6.1):
//! композитинг браузера добавляет 10–20 мс и отбирает контроль над
//! очередью кадров. Окно сессии — нативное, и Tauri про него не знает.

