//! Сырые биндинги к nvEncodeAPI.h, сгенерированные bindgen.
//!
//! Внутренний модуль: наружу не экспортируется ничего. Всё
//! взаимодействие с NVENC идёт через безопасные обёртки (CLAUDE.md §4.3.3).
//!
//! # Почему здесь отключены проверки
//!
//! Код машинный, править его нельзя, а `-D warnings` в CI иначе уронит
//! сборку. `unsafe_op_in_unsafe_fn` отключён по той же причине: bindgen
//! генерирует старый стиль, где тело `unsafe fn` целиком считается
//! небезопасным блоком.
//!
//! Это **единственное** место в проекте, где так можно — ровно потому,
//! что содержимое не написано человеком. Во всех рукописных модулях
//! правила §4.3 действуют без послаблений.

#![allow(warnings)]
#![allow(unsafe_op_in_unsafe_fn)]

include!(concat!(env!("OUT_DIR"), "/nvenc_bindings.rs"));
