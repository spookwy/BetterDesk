//! Захват экрана. `trait Capturer` и платформенные бэкенды.
//!
//! # Границы
//!
//! Наружу отдаётся **только** [`Capturer`] и типы из `bd-core`. Верхние
//! уровни (`bd-host`) не видят ни DXGI, ни `windows`-крейта, ни сырых
//! указателей — таково правило CLAUDE.md §4.2.2.
//!
//! `unsafe` здесь разрешён (§4.3.1), но каждый блок обязан нести
//! комментарий `// SAFETY:`, объясняющий соблюдённые инварианты C-API.
//!
//! # Два бэкенда, и почему оба нужны
//!
//! - **DXGI Desktop Duplication** — основной путь. Отдаёт GPU-текстуру
//!   без копии в RAM, самая низкая задержка.
//! - **Windows.Graphics.Capture (WGC)** — фоллбэк. DXGI требует, чтобы
//!   процесс исполнялся на том же адаптере, что и дисплей; на ноутбуках
//!   с гибридной графикой (а машина разработчика именно такая, CLAUDE.md
//!   §0.1) это регулярно ломается. WGC работает cross-GPU ценой чуть
//!   большей задержки.

#![deny(unsafe_op_in_unsafe_fn)]

mod error;

pub use error::{CaptureError, Result};

use bd_core::frame::FrameSize;
use std::time::Duration;

#[cfg(windows)]
pub mod windows;

/// Описание монитора, доступного для захвата.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MonitorInfo {
    /// Индекс выхода адаптера. Используется для выбора монитора.
    pub index: u32,
    /// Имя устройства, как его называет система (например, `\\.\DISPLAY1`).
    pub device_name: String,
    /// Разрешение в пикселях.
    pub size: FrameSize,
    /// Левый верхний угол монитора в координатах виртуального рабочего
    /// стола, в пикселях.
    ///
    /// У основного монитора это `(0, 0)`; у соседних координаты могут
    /// быть отрицательными, если экран стоит слева или выше основного.
    ///
    /// Нужны, чтобы соотнести монитор с общим пространством экранов:
    /// без них нельзя ни разместить окно на конкретном экране, ни
    /// пересчитать координаты мыши между хостом и клиентом
    /// (этап 2 — ввод, этап 11 — многомониторность).
    pub origin: (i32, i32),
    /// Основной ли это монитор.
    pub is_primary: bool,
}

/// Результат попытки захватить кадр.
///
/// Отсутствие кадра — **не ошибка**, а штатная ситуация: если на экране
/// ничего не изменилось, DXGI возвращает таймаут. Такой кадр не нужно
/// ни кодировать, ни отправлять (CLAUDE.md §5.1), поэтому это отдельный
/// вариант, а не `Err`.
#[derive(Debug)]
pub enum CaptureOutcome<F> {
    /// Получен новый кадр.
    Frame(F),
    /// Экран не изменился за отведённое время.
    Timeout,
}

/// Источник кадров экрана.
///
/// # Контракт по задержке
///
/// Реализация обязана отдавать поверхность, живущую в GPU. Копирование
/// в системную память запрещено (CLAUDE.md §4.2.3) — оно стоит 5–10 мс
/// и съедает треть бюджета задержки.
pub trait Capturer: Send {
    /// Тип кадра, специфичный для бэкенда.
    ///
    /// Ассоциированный тип, а не общий: у DXGI это D3D11-текстура, у
    /// будущих платформ будет своё. Верхние уровни работают с ним как
    /// с непрозрачным значением и передают дальше в энкодер.
    type Frame;

    /// Ждать следующий кадр не дольше `timeout`.
    ///
    /// Возвращает [`CaptureOutcome::Timeout`], если экран не изменился —
    /// это нормальный ход событий, а не ошибка.
    ///
    /// # Ошибки
    ///
    /// [`CaptureError::AccessLost`] означает, что сессию захвата надо
    /// пересоздать: сменилось разрешение, всплыл UAC, переключился GPU.
    /// Это происходит регулярно и **не является** исключительной
    /// ситуацией (CLAUDE.md §5.1).
    fn next_frame(&mut self, timeout: Duration) -> Result<CaptureOutcome<Self::Frame>>;

    /// Текущее разрешение источника.
    fn size(&self) -> FrameSize;

    /// Пересоздать сессию захвата после [`CaptureError::AccessLost`].
    fn recover(&mut self) -> Result<()>;
}
