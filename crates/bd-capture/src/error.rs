//! Ошибки захвата.
//!
//! Разделены по признаку «что с этим делать вызывающему», а не по тому,
//! какой код вернул Windows. Восстановимая потеря доступа и отсутствие
//! GPU требуют разной реакции, и тип ошибки должен это показывать.

/// Результат операций захвата.
pub type Result<T> = std::result::Result<T, CaptureError>;

/// Ошибка захвата экрана.
#[derive(Debug, thiserror::Error)]
pub enum CaptureError {
    /// Доступ к дупликации потерян — сессию нужно пересоздать.
    ///
    /// Причины штатные и частые: смена разрешения, переход на secure
    /// desktop (UAC, Ctrl+Alt+Del), блокировка экрана, переключение
    /// активного GPU, смена режима полноэкранного приложения.
    ///
    /// **Это не повод завершать работу.** Вызывающий обязан вызвать
    /// [`Capturer::recover`](crate::Capturer::recover) и продолжить
    /// (CLAUDE.md §5.1).
    #[error("доступ к дупликации потерян, требуется пересоздание сессии")]
    AccessLost,

    /// Дупликация недоступна, потому что её уже занял другой процесс.
    ///
    /// DXGI разрешает только одну сессию Desktop Duplication на выход.
    /// Типично при запущенном OBS или другом стримере.
    #[error("дупликация уже занята другим приложением")]
    Unavailable,

    /// Рабочий стол сейчас недоступен пользовательской сессии.
    ///
    /// Так выглядит **secure desktop**: UAC-диалог, Ctrl+Alt+Del,
    /// экран блокировки, экран смены пользователя. `DuplicateOutput`
    /// отвечает `E_ACCESSDENIED`, потому что пользовательская сессия
    /// не имеет права дуплицировать защищённый рабочий стол
    /// (CLAUDE.md §5.1).
    ///
    /// **Состояние временное и штатное.** Оно длится ровно столько,
    /// сколько пользователь смотрит на диалог, и заканчивается само.
    /// Единственно верная реакция — подождать и попробовать снова;
    /// завершать работу нельзя, иначе первый же UAC оборвёт сессию.
    ///
    /// Полностью снимается только захватом из службы (§3.2, этап 8).
    #[error("рабочий стол недоступен (secure desktop: UAC, блокировка)")]
    DesktopUnavailable,

    /// Запрошенный монитор не существует.
    #[error("монитор с индексом {index} не найден (доступно: {available})")]
    MonitorNotFound {
        /// Запрошенный индекс.
        index: u32,
        /// Сколько мониторов найдено.
        available: u32,
    },

    /// Не удалось инициализировать графическое устройство.
    ///
    /// В отличие от [`Self::AccessLost`], это не восстанавливается сама
    /// собой: нет подходящего адаптера, нет драйвера, отказано в доступе.
    #[error("не удалось инициализировать графическое устройство: {0}")]
    DeviceInit(String),

    /// Бэкенд не поддерживается на этой системе.
    ///
    /// Например, WGC требует Windows 10 1903+.
    #[error("бэкенд захвата не поддерживается: {0}")]
    Unsupported(String),

    /// Ошибка платформенного API, не подпадающая под остальные варианты.
    #[error("ошибка платформенного API: {context} (код {code:#010x})")]
    Platform {
        /// Что именно пытались сделать.
        context: &'static str,
        /// Код HRESULT.
        code: u32,
    },
}

impl CaptureError {
    /// Можно ли продолжить работу, пересоздав сессию.
    ///
    /// Позволяет вызывающему отличить «подожди и попробуй снова» от
    /// «дальше работать нельзя» без разбора вариантов вручную.
    pub fn is_recoverable(&self) -> bool {
        matches!(
            self,
            CaptureError::AccessLost | CaptureError::Unavailable | CaptureError::DesktopUnavailable
        )
    }

    /// Ждать ли, прежде чем пробовать снова.
    ///
    /// Отличает «пересоздай прямо сейчас» от «сейчас нельзя в принципе,
    /// приходи позже». Пересоздавать дупликацию в цикле, пока на экране
    /// UAC-диалог, бессмысленно: она не создастся, пока пользователь
    /// не ответит, а попытки будут жечь процессор десятками тысяч
    /// вызовов в секунду.
    pub fn needs_backoff(&self) -> bool {
        matches!(
            self,
            CaptureError::DesktopUnavailable | CaptureError::Unavailable
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn access_lost_is_recoverable() {
        // Смена разрешения и UAC случаются постоянно — если бы они
        // считались фатальными, сессия рвалась бы по десять раз на дню.
        assert!(CaptureError::AccessLost.is_recoverable());
        assert!(CaptureError::Unavailable.is_recoverable());
    }

    #[test]
    fn secure_desktop_is_recoverable_and_backs_off() {
        // Дефект, найденный на живом железе: UAC ронял процесс,
        // потому что `E_ACCESSDENIED` попадал в `Platform`, а тот
        // невосстановим. Пока UAC на экране, дупликация не создастся
        // ни с какой попытки — значит, ждать обязательно.
        let err = CaptureError::DesktopUnavailable;
        assert!(err.is_recoverable(), "UAC не должен завершать сессию");
        assert!(err.needs_backoff(), "повтор без паузы сожжёт процессор");
    }

    #[test]
    fn access_lost_retries_immediately() {
        // Смена разрешения, в отличие от UAC, проходит мгновенно:
        // пересоздавать надо сразу, а не через паузу, иначе кадры
        // встанут на ровном месте.
        assert!(!CaptureError::AccessLost.needs_backoff());
    }

    #[test]
    fn device_init_is_not_recoverable() {
        let err = CaptureError::DeviceInit("нет адаптера".into());
        assert!(!err.is_recoverable());
    }

    #[test]
    fn monitor_not_found_reports_both_numbers() {
        let err = CaptureError::MonitorNotFound {
            index: 5,
            available: 2,
        };
        let msg = err.to_string();
        assert!(msg.contains('5') && msg.contains('2'), "текст: {msg}");
    }
}
