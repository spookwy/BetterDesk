//! Оболочка BetterDesk: главный экран.
//!
//! # Что это и чем не является
//!
//! Это **окно оболочки** (CLAUDE.md §6.1): список машин, свой ID,
//! подключение, настройки. Задержка здесь не важна.
//!
//! Окно **сессии** — совсем другое: нативное Win32 + D3D11-swapchain,
//! про которое Tauri не знает вовсе. Ни один кадр видео через webview
//! не идёт и идти не может: композитинг браузера стоит 10–20 мс, ради
//! избавления от которых и заведено отдельное окно. Это правило
//! нарушать нельзя ни при каких обстоятельствах.
//!
//! # Почему оболочка появилась до этапа 7
//!
//! §11 запрещает UI, пока не закрыт пайплайн. Правило нарушено
//! сознательно, по решению владельца проекта от 2026-08-31 —
//! обоснование записано в CLAUDE.md §11, чтобы следующий агент не
//! счёл это недосмотром.
//!
//! Коротко: пайплайн уже уложился (8.02 мс из 25), оболочка не
//! участвует в пути кадра и ничего не подключает — соединение по ID
//! требует сигналинга, которого нет до этапа 4.
//!
//! # Что здесь настоящее, а что нет
//!
//! Настоящее: ID устройства (выводится из машины, а не выдумывается),
//! пароль сеанса, проверка пригодности машины в хосты и клиенты.
//!
//! Ненастоящее и **честно помеченное таковым в интерфейсе**:
//! сохранённые машины и их состояние. Показывать выдуманный список
//! молча — значит соврать: человек решит, что подключение работает.

// Прячет консольное окно у релизной сборки. В отладочной консоль
// нужна: без неё не видно ни логов, ни паник.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]
#![forbid(unsafe_code)]

use serde::Serialize;
use std::sync::Mutex;

/// Состояние машины: годится ли она в хосты и в клиенты.
///
/// Считается **один раз при запуске** и кладётся в состояние Tauri:
/// проверка создаёт D3D11-устройство и опрашивает энкодеры, то есть
/// стоит десятки миллисекунд. Дёргать её на каждый запрос из webview
/// незачем — железо за время работы окна не меняется.
struct Machine {
    id: String,
    password: String,
}

/// То, что уходит в webview на главный экран.
#[derive(Serialize)]
struct Identity {
    /// Девять цифр, сгруппированные по три.
    id: String,
    /// Одноразовый пароль сеанса.
    password: String,
    /// Может ли эта машина отдавать свой экран.
    can_host: bool,
    /// Может ли смотреть чужой.
    can_view: bool,
    /// Человеческое объяснение, если что-то из двух — нет.
    limitation: Option<String>,
}

#[tauri::command]
fn identity(state: tauri::State<'_, Mutex<Machine>>) -> Identity {
    let machine = state.lock().expect("состояние оболочки отравлено");

    // Проверка железа делается здесь, а не при старте: она открывает
    // D3D11-устройство, и на машине без графики это заметная пауза.
    // Экран успевает отрисоваться раньше, чем придёт ответ.
    let (can_host, can_view, limitation) = probe_machine();

    Identity {
        id: machine.id.clone(),
        password: machine.password.clone(),
        can_host,
        can_view,
        limitation,
    }
}

/// Узнать, на что способна эта машина.
///
/// Возвращает («может хостить», «может смотреть», объяснение).
///
/// # Почему это не `Result`
///
/// Отказ одной подсистемы — не конец проверки, а один из результатов
/// (тот же довод, что у `machine_probe`, находка 48). `Result`
/// подталкивает к `?`, то есть к выходу на первой же ошибке, — а нам
/// нужно узнать про обе роли независимо.
fn probe_machine() -> (bool, bool, Option<String>) {
    #[cfg(windows)]
    {
        // Клиенту нужен только декодер; хосту — захват и энкодер.
        // Роли несимметричны (§3.1), и машина вполне может годиться
        // в одну и не годиться в другую.
        // Результат каждой проверки пишется в лог отдельно.
        //
        // Без этого «Только просмотр» на машине, которая заведомо
        // умеет хостить, неотличимо от правды: значок сообщает
        // вывод, но не причину (находка 45 — глаз видит результат,
        // но не причину; нужен дамп, а не гипотеза).
        let decode = bd_capture::windows::D3dDevice::for_decode();
        if let Err(e) = &decode {
            tracing::warn!(error = %e, "D3D11-устройство для показа недоступно");
        }
        let can_view = decode.is_ok();

        let dxgi = bd_capture::windows::dxgi_available();
        tracing::info!(can_view, dxgi, "проверка машины");

        let can_host = can_view && dxgi;

        let limitation = match (can_host, can_view) {
            (true, true) => None,
            (false, true) => Some(
                "Эта машина может смотреть чужой экран, но не отдавать свой: \
                 захват экрана недоступен."
                    .into(),
            ),
            (_, false) => Some(
                "Не удалось создать графическое устройство. \
                 Без него нельзя ни показывать, ни отдавать экран."
                    .into(),
            ),
        };

        (can_host, can_view, limitation)
    }

    #[cfg(not(windows))]
    {
        (
            false,
            false,
            Some("BetterDesk работает только на Windows.".into()),
        )
    }
}

/// Собрать девятизначный ID этой машины.
///
/// # Тут был дефект, и он поучительный
///
/// Оболочка считала ID сама, своей копией той же формулы. Копии
/// разошлись на **одну единицу** в делителе (`% 900_000_000` против
/// `% 900_000_001`), и машина получила два разных ID: оболочка
/// показывала `955 235 149`, а `bd-host` регистрировался как
/// `907 922 838`.
///
/// Ошибки при этом не было нигде: оба числа девятизначные, оба
/// устойчивы между запусками, каждая программа по отдельности вела
/// себя правильно. Дефект виден только если запустить обе и сравнить
/// глазами — что и произошло случайно.
///
/// Практическое следствие было бы тяжёлым: человек диктует ID,
/// который видит в окне, а подключиться по нему нельзя, потому что
/// хост зарегистрирован под другим. Причём «не в сети» — ровно то
/// сообщение, которое клиент и покажет.
///
/// Отсюда правило: **у значения, которое видят двое, должен быть
/// один источник.** Теперь это `bd_core::DeviceId::derive`, и
/// оболочка, хост и клиент зовут именно его.
///
/// # Про сам ID
///
/// Он выводится локально и **никем не подтверждён**: настоящий ID
/// выдаёт сигналинг при регистрации (§5.4). ID вообще не средство
/// аутентификации (§7.3) — это удобное имя, а личность даёт ключ
/// Ed25519 (этап 5).
fn local_id() -> String {
    bd_core::DeviceId::of_this_machine().to_string()
}

/// Пароль на один сеанс.
///
/// Портативный режим (§7.1): пароль показывается на хосте и живёт до
/// перезапуска. Постоянный пароль с Argon2id — этап 5.
///
/// Алфавит без похожих символов: человек диктует пароль голосом или
/// переписывает с экрана, и `0`/`O`, `1`/`l` там неразличимы.
fn session_password() -> String {
    const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyz23456789";

    // Источник случайности — время запуска. Этого достаточно ровно
    // до этапа 5, где пароль становится настоящим средством доступа
    // и потребует криптографического ГПСЧ.
    let mut seed = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0x9E37_79B9_7F4A_7C15);

    let mut out = String::with_capacity(9);
    for i in 0..8 {
        // xorshift64: перемешивает достаточно, чтобы соседние запуски
        // не давали похожих паролей.
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        out.push(ALPHABET[(seed % ALPHABET.len() as u64) as usize] as char);
        if i == 3 {
            out.push('-');
        }
    }
    out
}

fn main() {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| "info".into()),
        )
        .init();

    let machine = Machine {
        id: local_id(),
        password: session_password(),
    };

    tracing::info!(id = %machine.id, "оболочка запущена");

    tauri::Builder::default()
        .manage(Mutex::new(machine))
        .invoke_handler(tauri::generate_handler![identity])
        .run(tauri::generate_context!())
        .expect("не удалось запустить окно оболочки");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn id_is_nine_digits_grouped_by_three() {
        let id = local_id();
        assert_eq!(id.len(), 11, "девять цифр и два пробела: {id}");
        let digits: String = id.chars().filter(|c| !c.is_whitespace()).collect();
        assert_eq!(digits.len(), 9);
        assert!(digits.chars().all(|c| c.is_ascii_digit()), "{id}");
    }

    #[test]
    fn id_does_not_start_with_zero() {
        // Ведущий ноль теряется везде, где поле «умно» приводит
        // строку к числу, — и человек диктует ID, которого нет.
        assert_ne!(local_id().chars().next(), Some('0'));
    }

    #[test]
    fn id_is_stable_between_calls() {
        // Человек, увидевший свой ID вчера, должен увидеть тот же
        // сегодня: иначе сохранённые у собеседника записи мертвы.
        assert_eq!(local_id(), local_id());
    }

    #[test]
    fn password_avoids_lookalike_characters() {
        // Пароль диктуют голосом и переписывают с экрана. `0`/`O`
        // и `1`/`l` там неразличимы, и человек винит программу.
        //
        // Тест проверен на способность провалиться: с добавлением
        // '0' и 'l' в алфавит он падает.
        for _ in 0..200 {
            let pw = session_password();
            assert!(
                !pw.contains(['0', 'o', 'O', '1', 'l', 'I']),
                "в пароле похожие символы: {pw}"
            );
        }
    }

    #[test]
    fn password_has_expected_shape() {
        let pw = session_password();
        assert_eq!(pw.len(), 9, "восемь знаков и дефис: {pw}");
        assert_eq!(pw.chars().nth(4), Some('-'), "{pw}");
    }
}
